#!/usr/bin/env node
/**
 * Heals node_modules after the Vly sync layer / platform install occasionally
 * drops files (e.g. ms/index.js, min-indent/index.js, truncated drizzle-orm,
 * missing @rollup/rollup-linux-x64-gnu .node binary).
 *
 * Runs automatically via the `postinstall` / `predev` / `prebuild` npm hooks,
 * so it executes no matter which package manager the platform uses.
 *
 * Restoration order:
 *   1. bun install cache (fast, local)
 *   2. unpkg CDN (https://unpkg.com/<pkg>@<version>/<file>)
 *   3. jsDelivr CDN (https://cdn.jsdelivr.net/npm/<pkg>@<version>/<file>)
 *
 * Binary files (.node, esbuild binary) are downloaded and written as Buffers.
 * Bounded: a small network budget keeps it fast even when many packages
 * declare legacy `main` entries that the published package never ships.
 * Never throws — installs/builds must not fail because of this script.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NM = path.join(ROOT, "node_modules");
const CACHE = path.join(process.env.HOME || "/home/daytona", ".bun", "install", "cache");
const EXT = ["", ".js", ".cjs", ".mjs", ".json", ".node", ".d.ts"];
const SKIP_DIRS = new Set([".bin", ".cache", ".vite", ".bun", ".yarn", ".pnpm", ".store"]);
const FETCH_TIMEOUT_MS = 10_000;
const MAX_NETWORK_ATTEMPTS = 8;
const MAX_ELAPSED_MS = 45_000;

const START = Date.now();
let networkAttempts = 0;
let restored = 0;

function log(msg) {
  console.log(`[heal-node_modules] ${msg}`);
}

function withinBudget() {
  return networkAttempts < MAX_NETWORK_ATTEMPTS && Date.now() - START < MAX_ELAPSED_MS;
}

/**
 * True when pkgDir is a real package root:
 *   node_modules/<name>            (unscoped)
 *   node_modules/<@scope>/<name>   (scoped)
 * Subpath stubs (e.g. hono/dist/types) are not roots.
 */
function isPackageRoot(pkgDir) {
  const parent = path.basename(path.dirname(pkgDir));
  if (parent === "node_modules") {
    // node_modules/<@scope> is a container for scoped packages, never a
    // package root itself (it legitimately has no package.json).
    return !path.basename(pkgDir).startsWith("@");
  }
  const gp = path.basename(path.dirname(path.dirname(pkgDir)));
  return parent.startsWith("@") && gp === "node_modules";
}

/** Returns the file path that must exist for `pkg` to load, or null. */
function entryPath(pkgJsonPath, pkg) {
  const dir = path.dirname(pkgJsonPath);
  if (pkg.exports && typeof pkg.exports === "object") {
    const dot = pkg.exports["."];
    if (typeof dot === "string") return path.join(dir, dot);
    if (Array.isArray(dot)) {
      for (const e of dot) if (typeof e === "string") return path.join(dir, e);
      return null;
    }
    if (dot && typeof dot === "object") {
      for (const key of ["types", "import", "require", "default", "bun", "node"]) {
        const v = dot[key];
        if (typeof v === "string") return path.join(dir, v);
      }
    }
    // Subpath-only exports (e.g. math-intrinsics) — no root entry to check.
    return null;
  }
  if (typeof pkg.main === "string" && pkg.main.length > 0) {
    return path.join(dir, pkg.main);
  }
  // Type-only packages (csstype) and @types/* declare `types` with an empty
  // main — tsc resolves those via the `types` field.
  for (const key of ["types", "typings"]) {
    const t = pkg[key];
    if (typeof t === "string" && t.length > 0) return path.join(dir, t);
  }
  // No declared entry: Node falls back to index.js regardless of module
  // type (e.g. redent@3.0.0 ships index.js with no main/exports field).
  return path.join(dir, "index.js");
}

function isMissing(absPath) {
  if (fs.existsSync(absPath)) return false;
  for (const ext of EXT) {
    if (fs.existsSync(absPath + ext)) return false;
  }
  return true;
}

/** Memoized readdir for cache dirs (findCache now runs per package). */
const cacheListings = new Map();
function listCacheDir(dir) {
  if (!cacheListings.has(dir)) {
    try {
      cacheListings.set(dir, fs.readdirSync(dir));
    } catch {
      cacheListings.set(dir, []);
    }
  }
  return cacheListings.get(dir);
}

/** Reads a cache entry's package.json version, or null. */
function cacheVersion(p) {
  try {
    return JSON.parse(fs.readFileSync(path.join(p, "package.json"), "utf8")).version;
  } catch {
    return null;
  }
}

/** Scans one cache directory for <name>@<version>, returning the dir or null. */
function matchInDir(dir, name, version) {
  if (!fs.existsSync(dir)) return null;
  let best = null;
  const entries = listCacheDir(dir);
  for (const entry of entries) {
    if (!entry.startsWith(name + "@")) continue;
    const p = path.join(dir, entry);
    if (!fs.statSync(p).isDirectory()) continue;
    const v = cacheVersion(p);
    if (v === version) return p;
    if (!best) best = p;
  }
  // Some bun cache layouts nest versioned entries under <dir>/<name>/,
  // e.g. ~/.bun/install/cache/@types/better-sqlite3/7.6.13@@@1/.
  const nested = path.join(dir, name);
  if (fs.existsSync(nested) && fs.statSync(nested).isDirectory()) {
    for (const entry of listCacheDir(nested)) {
      const p = path.join(nested, entry);
      if (!fs.statSync(p).isDirectory()) continue;
      const v = cacheVersion(p);
      if (v === version) return p;
      if (!best) best = p;
    }
  }
  return best;
}

/** Full package name (including scope) for a package root dir. */
function packageNameOf(pkgDir) {
  const parent = path.basename(path.dirname(pkgDir));
  const base = path.basename(pkgDir);
  return parent.startsWith("@") ? `${parent}/${base}` : base;
}

/**
 * Finds an exact-install cache entry for a package by name when the version
 * is unknown (the installed package.json was dropped). If pkgDir still holds
 * some files, prefers the entry whose file set covers the most of them, so a
 * cache that holds multiple versions picks the one that was actually
 * installed.
 */
function findCacheByName(name, pkgDir) {
  if (!fs.existsSync(CACHE)) return null;
  const candidates = [];
  const consider = (p) => {
    try {
      if (fs.statSync(p).isDirectory() && fs.existsSync(path.join(p, "package.json"))) {
        candidates.push(p);
      }
    } catch {
      /* ignore */
    }
  };
  if (name.startsWith("@")) {
    const [scope, rest] = name.split("/");
    // CACHE/<scope>/<rest>/<version>@@@<hash>
    const nested = path.join(CACHE, scope, rest);
    if (fs.existsSync(nested) && fs.statSync(nested).isDirectory()) {
      for (const entry of listCacheDir(nested)) consider(path.join(nested, entry));
    }
    // CACHE/<scope>/<rest>@<version>@@@<hash>
    const scopeDir = path.join(CACHE, scope);
    if (fs.existsSync(scopeDir)) {
      for (const entry of listCacheDir(scopeDir)) {
        if (entry.startsWith(rest + "@")) consider(path.join(scopeDir, entry));
      }
    }
  } else {
    // CACHE/<name>@<version>@@@<hash>
    for (const entry of listCacheDir(CACHE)) {
      if (entry.startsWith(name + "@")) consider(path.join(CACHE, entry));
    }
    // CACHE/<name>/<version>@@@<hash>
    const plain = path.join(CACHE, name);
    if (fs.existsSync(plain) && fs.statSync(plain).isDirectory()) {
      for (const entry of listCacheDir(plain)) consider(path.join(plain, entry));
    }
  }
  if (candidates.length === 0) return null;
  if (pkgDir && fs.existsSync(pkgDir)) {
    let existing = [];
    try {
      existing = fs.readdirSync(pkgDir);
    } catch {
      existing = [];
    }
    candidates.sort((a, b) => {
      const inA = existing.filter((f) => fs.existsSync(path.join(a, f))).length;
      const inB = existing.filter((f) => fs.existsSync(path.join(b, f))).length;
      return inB - inA;
    });
  }
  return candidates[0];
}

/** Finds a cache dir for a package name + version (handles @scope nesting). */
function findCache(name, version) {
  if (!fs.existsSync(CACHE)) return null;
  if (name.startsWith("@")) {
    const [scope, rest] = name.split("/");
    return (
      matchInDir(path.join(CACHE, scope), rest, version) ||
      matchInDir(CACHE, name, version)
    );
  }
  return matchInDir(CACHE, name, version);
}

async function fetchWithTimeout(url, timeoutMs = FETCH_TIMEOUT_MS) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: ac.signal, redirect: "follow" });
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
    return Buffer.from(await res.arrayBuffer());
  } finally {
    clearTimeout(t);
  }
}

/** Downloads <relPath> of pkg@version from the CDN fallbacks. Returns Buffer or null. */
async function download(pkgName, version, relPath) {
  networkAttempts++;
  const clean = relPath.replace(/^\.\//, "");
  // Empty version → latest (used when restoring a dropped package.json whose
  // installed version cannot be known).
  const ver = version ? `${pkgName}@${version}` : pkgName;
  const urls = [
    `https://unpkg.com/${ver}/${clean}`,
    `https://cdn.jsdelivr.net/npm/${ver}/${clean}`,
  ];
  for (const url of urls) {
    try {
      const buf = await fetchWithTimeout(url);
      if (buf.length > 0) return buf;
    } catch (err) {
      log(`download failed (${url}): ${err.message}`);
    }
  }
  return null;
}

/** Reconciles a package's install dir against its exact-version bun cache
 *  entry, restoring anything the sync layer dropped (entries, chunk files,
 *  subpath package.json, @types/* definitions, esbuild binaries, whole
 *  missing dirs). Cache-only, never overwrites. Budget-bounded. */
async function syncFromCache(pkgName, version, pkgDir, cache) {
  let restoredHere = 0;
  async function syncDir(cDir, nDir) {
    if (Date.now() - START > MAX_ELAPSED_MS || restoredHere >= 300) return;
    let entries;
    try {
      entries = fs.readdirSync(cDir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const ent of entries) {
      if (restoredHere >= 300) return;
      const cP = path.join(cDir, ent.name);
      const nP = path.join(nDir, ent.name);
      if (ent.isDirectory()) {
        if (fs.existsSync(nP)) {
          await syncDir(cP, nP);
        } else {
          try {
            fs.cpSync(cP, nP, { recursive: true });
            log(`restored ${path.relative(NM, nP)}/ (from cache)`);
            restored++;
            restoredHere++;
          } catch (err) {
            log(`cache restore failed for ${path.relative(NM, nP)}/: ${err.message}`);
          }
        }
      } else if (!fs.existsSync(nP)) {
        restoredHere++;
        try {
          fs.mkdirSync(path.dirname(nP), { recursive: true });
          fs.copyFileSync(cP, nP);
          log(`restored ${path.relative(NM, nP)} (from cache)`);
          restored++;
        } catch (err) {
          log(`cache restore failed for ${path.relative(NM, nP)}: ${err.message}`);
        }
      }
    }
  }
  await syncDir(cache, pkgDir);
}

/** Restores an empty subdirectory of a package (npm never ships empty dirs,
 *  so these are truncations, e.g. react-remove-scroll-bar/constants losing its
 *  package.json). Prefers the whole dir from the bun cache; falls back to
 *  fetching the subpath package.json from the CDN and restoring its main. */
async function restoreEmptyDir(pkgName, version, pkgDir, missingDir) {
  const rel = path.relative(pkgDir, missingDir);
  const cache = findCache(pkgName, version);
  if (cache) {
    const src = path.join(cache, rel);
    if (fs.existsSync(src)) {
      try {
        fs.cpSync(src, missingDir, { recursive: true });
        log(`restored ${path.relative(NM, missingDir)}/ (from cache)`);
        restored++;
        return;
      } catch (err) {
        log(`cache restore failed for ${rel}/: ${err.message}`);
      }
    }
  }
  if (!withinBudget()) {
    log(`skipping ${rel}/ (network budget exhausted)`);
    return;
  }
  const buf = await download(pkgName, version, `${rel}/package.json`);
  if (!buf) {
    log(`no source for ${pkgName}@${version} (${rel}/)`);
    return;
  }
  let subPkg;
  try {
    subPkg = JSON.parse(buf.toString("utf8"));
  } catch {
    return;
  }
  fs.mkdirSync(missingDir, { recursive: true });
  fs.writeFileSync(path.join(missingDir, "package.json"), buf);
  log(`restored ${path.relative(NM, missingDir)}/package.json (from CDN)`);
  restored++;
  const main = typeof subPkg.main === "string" ? subPkg.main : "index.js";
  const abs = path.join(missingDir, main);
  if (isMissing(abs)) {
    await restoreFile(pkgName, version, abs, pkgDir);
  }
}

/** Restores one missing file. Returns true on success. */
async function restoreFile(pkgName, version, missingAbs, pkgDir) {
  const rel = path.relative(NM, missingAbs);
  // 1. bun cache
  const cache = findCache(pkgName, version);
  if (cache) {
    let src = path.join(cache, path.relative(pkgDir, missingAbs));
    // main: "./index" resolves to index.js — the cache stores the real filename.
    if (!fs.existsSync(src)) {
      for (const ext of EXT) {
        if (fs.existsSync(src + ext)) {
          src = src + ext;
          break;
        }
      }
    }
    if (fs.existsSync(src)) {
      try {
        fs.mkdirSync(path.dirname(missingAbs), { recursive: true });
        fs.copyFileSync(src, missingAbs);
        log(`restored ${rel} (from cache)`);
        restored++;
        return true;
      } catch (err) {
        log(`cache restore failed for ${rel}: ${err.message}`);
      }
    }
  }
  // 2./3. CDN fallback (bounded). If the exact-version cache exists but the
  // file is not in it, the published package never shipped it (types-only
  // packages, platform stubs) — don't waste the network budget.
  if (cache && !fs.existsSync(path.join(cache, path.relative(pkgDir, missingAbs)))) {
    log(`no source for ${pkgName}@${version} (${path.relative(pkgDir, missingAbs)})`);
    return false;
  }
  if (!withinBudget()) {
    log(`skipping ${rel} (network budget exhausted)`);
    return false;
  }
  const buf = await download(pkgName, version, path.relative(pkgDir, missingAbs));
  if (buf) {
    try {
      fs.mkdirSync(path.dirname(missingAbs), { recursive: true });
      fs.writeFileSync(missingAbs, buf);
      log(`restored ${rel} (from CDN)`);
      restored++;
      return true;
    } catch (err) {
      log(`CDN restore failed for ${rel}: ${err.message}`);
    }
  } else {
    log(`no source for ${pkgName}@${version} (${path.relative(pkgDir, missingAbs)})`);
  }
  return false;
}

/**
 * Restores a package root whose package.json was dropped by the sync layer.
 * Without it the walk never visits the package, and tsc's @types resolution
 * can break (e.g. @types/better-sqlite3 under bundler module resolution).
 * Restores package.json from the exact-install cache entry, then reconciles
 * the whole tree from that entry. Falls back to the CDN (latest) only when
 * no cache entry exists.
 */
async function restorePkgJson(pkgDir) {
  const name = packageNameOf(pkgDir);
  const cache = findCacheByName(name, pkgDir);
  if (cache) {
    try {
      fs.mkdirSync(pkgDir, { recursive: true });
      fs.copyFileSync(path.join(cache, "package.json"), path.join(pkgDir, "package.json"));
      log(`restored ${path.relative(NM, path.join(pkgDir, "package.json"))} (from cache)`);
      restored++;
      const version = cacheVersion(cache);
      if (version) await syncFromCache(name, version, pkgDir, cache);
    } catch (err) {
      log(`cache restore failed for ${path.relative(NM, pkgDir)}: ${err.message}`);
    }
    return;
  }
  if (!withinBudget()) {
    log(`skipping ${path.relative(NM, pkgDir)}/package.json (network budget exhausted)`);
    return;
  }
  const buf = await download(name, "", "package.json");
  if (buf) {
    try {
      fs.mkdirSync(pkgDir, { recursive: true });
      fs.writeFileSync(path.join(pkgDir, "package.json"), buf);
      log(`restored ${path.relative(NM, path.join(pkgDir, "package.json"))} (from CDN)`);
      restored++;
    } catch (err) {
      log(`CDN restore failed for ${path.relative(NM, pkgDir)}/package.json: ${err.message}`);
    }
  } else {
    log(`no source for ${name} (package.json)`);
  }
}

async function walk(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  // Package root whose package.json was dropped: restore it (and reconcile
  // the whole tree from cache) before processing, so the package is visited.
  if (isPackageRoot(dir) && !fs.existsSync(path.join(dir, "package.json"))) {
    await restorePkgJson(dir);
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
  }
  for (const ent of entries) {
    if (ent.name.startsWith(".") || SKIP_DIRS.has(ent.name)) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      await walk(p);
      continue;
    }
    if (ent.name !== "package.json") continue;

    const pkgDir = path.dirname(p);
    // Subpath stubs (e.g. hono/dist/types/package.json) are not package roots.
    if (!isPackageRoot(pkgDir)) continue;

    let pkg;
    try {
      pkg = JSON.parse(fs.readFileSync(p, "utf8"));
    } catch {
      continue;
    }
    const name = pkg.name || path.basename(pkgDir);
    // Fast path: the bun cache has the exact version — reconcile the whole
    // tree (covers truncated entries, internal chunk files, subpath
    // package.json, @types/* definitions, esbuild binaries, empty dirs).
    const cache = findCache(name, pkg.version);
    if (cache) {
      await syncFromCache(name, pkg.version, pkgDir, cache);
      continue;
    }
    // Cache-less fallback: restore known entry points via CDN (bounded).
    const entry = entryPath(p, pkg);
    if (entry && isMissing(entry)) {
      await restoreFile(name, pkg.version, entry, pkgDir);
    }
    // tsc also resolves implicit sibling declarations of the runtime entry
    // (dist/index.js → dist/index.d.ts).
    if (entry) {
      const ext = path.extname(entry);
      const base = ext ? entry.slice(0, -ext.length) : entry;
      for (const cand of [entry + ".d.ts", entry + ".d.mts", base + ".d.ts", base + ".d.mts"]) {
        if (isMissing(cand)) {
          await restoreFile(name, pkg.version, cand, pkgDir);
        }
      }
    }
    // Empty subdirectories are truncation signatures (npm never publishes
    // empty dirs) — restore them so subpath imports resolve again.
    let sub;
    try {
      sub = fs.readdirSync(pkgDir, { withFileTypes: true });
    } catch {
      sub = [];
    }
    for (const s of sub) {
      if (!s.isDirectory() || SKIP_DIRS.has(s.name)) continue;
      const subPath = path.join(pkgDir, s.name);
      let contents;
      try {
        contents = fs.readdirSync(subPath);
      } catch {
        continue;
      }
      if (contents.length === 0) {
        await restoreEmptyDir(name, pkg.version, pkgDir, subPath);
      }
    }
    // @esbuild/* platform binaries declare no main/exports; esbuild loads bin/esbuild directly.
    if (name && name.startsWith("@esbuild/")) {
      const bin = path.join(pkgDir, "bin", "esbuild");
      if (!fs.existsSync(bin)) {
        await restoreFile(name, pkg.version, bin, pkgDir);
      }
    }
  }
}

if (!fs.existsSync(NM)) {
  log("node_modules not present; nothing to heal");
  process.exit(0);
}

await walk(NM);
log(restored > 0 ? `${restored} file(s) restored` : "all main entries present");
