#!/usr/bin/env node
/**
 * Heals node_modules after the Vly sync layer occasionally drops files
 * (e.g. ms/index.js, min-indent/index.js, truncated drizzle-orm).
 *
 * Runs automatically via the `postinstall` / `predev` / `prebuild` npm hooks.
 * It scans every package.json under node_modules, and when the package's
 * declared main entry is missing, restores it from the bun install cache.
 * Never throws — installs must not fail because of this.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NM = path.join(ROOT, "node_modules");
const CACHE = path.join(process.env.HOME || "/home/daytona", ".bun", "install", "cache");
const EXT = ["", ".js", ".cjs", ".mjs", ".json", ".node", ".d.ts"];
const SKIP_DIRS = new Set([".bin", ".cache", ".vite", ".bun", ".yarn", ".pnpm", ".store"]);

function log(msg) {
  console.log(`[heal-node_modules] ${msg}`);
}

/** Returns the expected main file path if it is missing, else null. */
function missingMain(pkgJsonPath, main) {
  const base = path.resolve(path.dirname(pkgJsonPath), main || "index.js");
  if (fs.existsSync(base)) return null;
  for (const ext of EXT) {
    if (fs.existsSync(base + ext)) return null;
  }
  return base;
}

/** Finds a cache dir for an unscoped package name + version. */
function findCache(name, version) {
  if (!fs.existsSync(CACHE)) return null;
  let best = null;
  let entries;
  try {
    entries = fs.readdirSync(CACHE);
  } catch {
    return null;
  }
  for (const dir of entries) {
    if (!dir.startsWith(name + "@")) continue;
    const p = path.join(CACHE, dir);
    let v = null;
    try {
      v = JSON.parse(fs.readFileSync(path.join(p, "package.json"), "utf8")).version;
    } catch {
      /* ignore */
    }
    if (v === version) return p;
    if (!best) best = p;
  }
  return best;
}

let restored = 0;

function walk(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const ent of entries) {
    if (ent.name.startsWith(".") || SKIP_DIRS.has(ent.name)) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      walk(p);
      continue;
    }
    if (ent.name !== "package.json") continue;

    let pkg;
    try {
      pkg = JSON.parse(fs.readFileSync(p, "utf8"));
    } catch {
      continue;
    }
    const missing = missingMain(p, pkg.main);
    if (!missing) continue;

    const name = pkg.name || path.basename(path.dirname(p));
    const cache = findCache(name, pkg.version);
    if (!cache) {
      log(`no cache entry for ${name}@${pkg.version} (missing ${path.basename(missing)})`);
      continue;
    }
    const src = path.join(cache, path.basename(missing));
    if (!fs.existsSync(src)) {
      log(`cache entry for ${name}@${pkg.version} lacks ${path.basename(missing)}`);
      continue;
    }
    try {
      fs.mkdirSync(path.dirname(missing), { recursive: true });
      fs.copyFileSync(src, missing);
      log(`restored ${path.relative(NM, missing)}`);
      restored++;
    } catch (err) {
      log(`failed to restore ${path.relative(NM, missing)}: ${err.message}`);
    }
  }
}

// drizzle-orm is a big package that has been observed truncated mid-extraction
// (sqlite-core subdirectory missing entirely). Repair whole missing top-level
// entries from the cache when that happens.
const drizzle = path.join(NM, "drizzle-orm");
if (fs.existsSync(path.join(drizzle, "package.json"))) {
  let pkg;
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(drizzle, "package.json"), "utf8"));
  } catch {
    pkg = null;
  }
  const cache = pkg ? findCache("drizzle-orm", pkg.version) : null;
  if (cache) {
    let cacheEntries;
    try {
      cacheEntries = fs.readdirSync(cache);
    } catch {
      cacheEntries = [];
    }
    for (const ent of cacheEntries) {
      const dest = path.join(drizzle, ent);
      if (!fs.existsSync(dest)) {
        try {
          fs.cpSync(path.join(cache, ent), dest, { recursive: true });
          log(`restored drizzle-orm/${ent}`);
          restored++;
        } catch (err) {
          log(`failed to restore drizzle-orm/${ent}: ${err.message}`);
        }
      }
    }
  }
}

if (!fs.existsSync(NM)) {
  log("node_modules not present; nothing to heal");
  process.exit(0);
}

walk(NM);
log(restored > 0 ? `${restored} file(s) restored` : "all main entries present");
